        await page.locator('.planner-topic[data-topic="glass-skin"]').click();await page.locator('.tz-creator-controls').waitFor({state:'visible'});
        assert.equal(await page.locator('.planner-progress').getAttribute('data-planner-step'),'2');
        await page.selectOption('[name=product_id]','mb-fresh-unspecified');await page.getByRole('button',{name:'View candidates',exact:true}).click();
        await page.waitForFunction(()=>document.querySelector('.planner-progress').dataset.plannerStep==='3');
        await screenshot('09-planner-creators','#creator-heading');checks++;
