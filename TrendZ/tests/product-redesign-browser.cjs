        assert.equal(await page.locator('#trend-grid img, #trend-grid script').count(),0);assert.equal(await page.evaluate(()=>window.injected),undefined);checks++;
        assert.deepEqual(errors,[]);
        const result={checks,page_errors:errors,observed_cards:8,card_states_match_api:true,backend_analytics_changed:false};
