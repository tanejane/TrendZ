        await page.getByRole('button',{name:'Makeup',exact:true}).click();
        assert(await page.locator('.trend-card').evaluateAll(es=>es.every(e=>e.dataset.category==='makeup')));
        await page.getByRole('button',{name:'All trends',exact:true}).click();
