        assert(await page.locator('.trend-card[data-topic="glass-skin"]').count());await screenshot('06-watchlist-populated');checks++;
        await page.route('**/api/watchlist',r=>r.fulfill({json:{status:'success',watchlist:[],data_mode:'real'}}));
        await page.reload();await cards();
        assert(await page.getByRole('heading',{name:'Your watchlist is empty',exact:true}).isVisible());
        assert(await page.getByRole('link',{name:'Explore trends',exact:true}).isVisible());
        assert.equal(await page.locator('.trend-card').count(),0);await screenshot('07-watchlist-empty');
        await page.unroute('**/api/watchlist');checks++;
        await page.getByRole('link',{name:'Explore trends',exact:true}).click();await cards();
        await page.locator('.trend-card[data-topic="glass-skin"]').getByRole('link',{name:'Explore Trend',exact:true}).click();
